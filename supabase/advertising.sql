-- HBU direct advertising requests and approved home-screen ad.
-- Run once in the Supabase SQL editor. Deploy the updated send-message Edge Function
-- so the Owner app can review requests.

create table if not exists public.hbu_ad_requests (
  id bigint generated by default as identity primary key,
  advertiser_name text not null,
  contact text not null,
  image_data text not null,
  target_url text not null,
  duration_days integer not null check (duration_days between 1 and 30),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'expired')),
  requested_at timestamptz not null default now(),
  starts_at timestamptz,
  expires_at timestamptz,
  reviewed_at timestamptz,
  reviewed_by text
);

create index if not exists hbu_ad_requests_status_requested_idx
  on public.hbu_ad_requests (status, requested_at desc);
create index if not exists hbu_ad_requests_contact_requested_idx
  on public.hbu_ad_requests (lower(contact), requested_at desc);

alter table public.hbu_ad_requests enable row level security;
revoke all on public.hbu_ad_requests from anon, authenticated;
grant all on public.hbu_ad_requests to service_role;
grant usage, select on sequence public.hbu_ad_requests_id_seq to service_role;

create or replace function public.hbu_submit_ad(
  p_advertiser_name text,
  p_contact text,
  p_image_data text,
  p_target_url text,
  p_duration_days integer
)
returns bigint
language plpgsql
security definer
set search_path = public, extensions
as $$
declare new_id bigint;
begin
  if length(trim(coalesce(p_advertiser_name, ''))) < 2
     or length(trim(p_advertiser_name)) > 60 then
    raise exception 'Enter an advertiser or business name (2-60 characters).';
  end if;
  if length(trim(coalesce(p_contact, ''))) < 3
     or length(trim(p_contact)) > 160 then
    raise exception 'Enter contact information (3-160 characters).';
  end if;
  if p_image_data is null
     or length(p_image_data) > 900000
     or p_image_data !~ '^data:image/(png|jpeg|webp|gif);base64,[A-Za-z0-9+/]+=*$' then
    raise exception 'Upload a PNG, JPG, WEBP, or GIF image no larger than 650 KB.';
  end if;
  if p_target_url is null
     or length(p_target_url) > 2048
     or p_target_url !~ '^https://[^[:space:]]+$' then
    raise exception 'The ad destination must be a valid HTTPS link.';
  end if;
  if p_duration_days is null or p_duration_days < 1 or p_duration_days > 30 then
    raise exception 'Choose an ad duration from 1 to 30 days.';
  end if;
  if (select count(*) from public.hbu_ad_requests
      where lower(contact) = lower(trim(p_contact))
        and requested_at > now() - interval '24 hours') >= 3 then
    raise exception 'This contact has already submitted 3 requests in the last 24 hours.';
  end if;

  insert into public.hbu_ad_requests
    (advertiser_name, contact, image_data, target_url, duration_days)
  values
    (trim(p_advertiser_name), trim(p_contact), p_image_data, trim(p_target_url), p_duration_days)
  returning id into new_id;
  return new_id;
end;
$$;

create or replace function public.hbu_get_active_ad()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
declare result jsonb;
begin
  select jsonb_build_object(
    'id', id,
    'advertiser_name', advertiser_name,
    'image_data', image_data,
    'target_url', target_url,
    'starts_at', starts_at,
    'expires_at', expires_at
  )
  into result
  from public.hbu_ad_requests
  where status = 'approved'
    and starts_at <= now()
    and expires_at > now()
  order by starts_at desc, id desc
  limit 1;
  return result;
end;
$$;

revoke all on function public.hbu_submit_ad(text, text, text, text, integer) from public;
revoke all on function public.hbu_get_active_ad() from public;
grant execute on function public.hbu_submit_ad(text, text, text, text, integer) to anon, authenticated;
grant execute on function public.hbu_get_active_ad() to anon, authenticated;

notify pgrst, 'reload schema';
